/**
 * 03 선택 기준 한 칸.
 * 번호(01·02·03)는 카피가 아니라 나열 순서에서 파생되므로 여기에 두지 않는다.
 * 위계는 키워드 > 설명 > 질문이다 — 인용(질문)이 답(설명)보다 작다
 * (화면설계 §5.1). 질문은 발주자의 말을 그대로 옮긴 것이라
 * 따옴표를 문안에 포함해 렌더한다 — 섹션 2 의 R1 과 같은 방식이다 (POL-13).
 */
type Criterion = {
  /** 발주자가 던지는 질문. 따옴표까지가 문안이다 */
  readonly question: string;
  /** 답의 핵심. 요구사항정의서 §2.4 확정 소구점 1·2·3 에 1:1 대응한다 */
  readonly keyword: string;
  /** 키워드가 무엇을 뜻하는지 한 문장으로 푼다 */
  readonly description: string;
};

/**
 * 프로세스 묶음 한 칸. 8단계를 넷으로 묶은 것이고, 값은 P-09 가 갖고 있던 것을
 * 그대로 옮겼다 (`app/process/p09-copy.ts` processCopy.groups).
 *
 * 별도 번호(1~4 · ①②③④)를 갖지 않는다. 번호는 `eyebrow` 의 「STEP 01–02」 안에
 * 단계 번호로 이미 들어 있고, 묶음에 1~4 를 따로 붙이면 8단계가 아니라
 * 4단계 프로세스로 읽힌다 (P-09 와 같은 판단).
 */
type ProcessGroup = {
  /** 「STEP 01–02」. 붙임표는 en dash(–) 다. hyphen 으로 바꾸지 않는다 */
  readonly eyebrow: string;
  readonly name: string;
  readonly summary: string;
};

