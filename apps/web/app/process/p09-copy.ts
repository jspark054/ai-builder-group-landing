/** 8단계 프로세스 한 칸. 번호는 나열 순서에서 파생되므로 여기에 두지 않는다. */
type ProcessStep = {
  readonly label: string;
  readonly description: string;
};

/**
 * 단계 묶음. 「STEP 01–02」 표기를 갖고 별도 번호는 갖지 않는다.
 * 묶음에 1~4 나 ①②③④ 를 붙이면 8단계가 아니라 4단계 프로세스로 읽힌다 (FN-P09-02).
 */
type ProcessGroup = {
  readonly eyebrow: string;
  readonly name: string;
  /**
   * 이 묶음을 **나가는** 관문 문구. 마지막 묶음에는 없다 (그 자리는 `gate.closing` 이 맡는다).
   *
   * 8/22 에 `entryNote`(다음 묶음의 입구)에서 이름과 자리가 함께 바뀌었다.
   * 같은 경계를 가리키는 같은 문장이고 붙는 쪽만 앞 묶음으로 옮겼다 — 목업이
   * 관문 문구를 묶음 좌측 칸에 넣으면서 「이 묶음이 끝나면 무엇을 확인하는가」가 됐다.
   * 문안 3건은 그대로다.
   */
  readonly exitNote?: string;
  readonly steps: readonly ProcessStep[];
};

